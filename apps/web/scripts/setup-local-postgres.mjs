import { randomBytes } from 'node:crypto';
import { chmodSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const appDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(appDirectory, '.env');
const databaseName = 'warriors_management';
const appRole = 'app_user';
const adminRole = 'warriors_admin';
const secrets = [];

function readEnvFile() {
  if (!existsSync(envPath)) return {};
  const values = {};
  for (const line of readFileSync(envPath, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (match) values[match[1]] = match[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return values;
}

function parseLocalUrl(value, expectedRole) {
  if (!value) return null;
  try {
    const url = new URL(value);
    if (
      url.protocol !== 'postgresql:' ||
      url.hostname !== '127.0.0.1' ||
      url.port !== '5432' ||
      url.pathname !== `/${databaseName}` ||
      decodeURIComponent(url.username) !== expectedRole ||
      !url.password
    ) {
      return null;
    }
    return url;
  } catch {
    return null;
  }
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: appDirectory,
    encoding: 'utf8',
    ...options,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    const output = `${result.stdout ?? ''}${result.stderr ?? ''}`.trim();
    throw new Error(output || `${command} exited with status ${result.status}`);
  }
  return result.stdout.trim();
}

function sqlLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function createSecret() {
  return randomBytes(32).toString('hex');
}

async function main() {
  run('pg_isready', []);

  const sudo = spawnSync('sudo', ['-v'], { stdio: 'inherit' });
  if (sudo.error) throw sudo.error;
  if (sudo.status !== 0) {
    throw new Error('Relancez cette commande depuis un terminal pour autoriser sudo.');
  }

  const currentEnv = readEnvFile();
  const adminUrl = parseLocalUrl(currentEnv.DATABASE_URL, adminRole);
  const reuseLocalConfig = Boolean(adminUrl && currentEnv.JWT_SECRET);

  const inventory = run('sudo', [
    '-n', '-u', 'postgres', 'psql', '-X', '-At', '-d', 'postgres', '-c',
    `SELECT
      EXISTS (SELECT 1 FROM pg_database WHERE datname = '${databaseName}')::int || '|' ||
      EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${appRole}')::int || '|' ||
      EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${adminRole}')::int`,
  ]);
  const [databaseExists, appRoleExists, adminRoleExists] = inventory.split('|').map(Number);

  if (!reuseLocalConfig && (databaseExists || appRoleExists || adminRoleExists)) {
    throw new Error(
      `La base ou les rôles ${databaseName}/${appRole}/${adminRole} existent déjà. ` +
        'Aucune donnée ni configuration n’a été modifiée. Vérifiez-les avant de relancer.'
    );
  }

  const adminPassword = adminUrl ? decodeURIComponent(adminUrl.password) : createSecret();
  const jwtSecret =
    reuseLocalConfig ? currentEnv.JWT_SECRET : createSecret();
  secrets.push(adminPassword, jwtSecret);
  const databaseUrl = `postgresql://${adminRole}:${adminPassword}@127.0.0.1:5432/${databaseName}?schema=public`;
  secrets.push(databaseUrl);

  const roleSql = `DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = '${adminRole}') THEN
    CREATE ROLE ${adminRole} LOGIN PASSWORD ${sqlLiteral(adminPassword)}
      NOSUPERUSER NOCREATEDB NOCREATEROLE BYPASSRLS NOREPLICATION;
  ELSE
    ALTER ROLE ${adminRole} WITH LOGIN PASSWORD ${sqlLiteral(adminPassword)} BYPASSRLS;
  END IF;
END
$$;

SELECT 'CREATE DATABASE ${databaseName} OWNER ${adminRole}'
WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = '${databaseName}')\\gexec
`;
  run('sudo', ['-n', '-u', 'postgres', 'psql', '-X', '-v', 'ON_ERROR_STOP=1', '-d', 'postgres'], {
    input: roleSql,
  });

  writeFileSync(
    envPath,
    [
      '# Local PostgreSQL development configuration. Regenerated by db:setup:local.',
      `DATABASE_URL="${databaseUrl}"`,
      `JWT_SECRET="${jwtSecret}"`,
      '',
    ].join('\n'),
    { mode: 0o600 }
  );
  chmodSync(envPath, 0o600);

  run('npm', ['run', 'db:push']);
  run('npm', ['run', 'db:migrate:compat']);

  const rlsSql = readFileSync(path.join(appDirectory, 'db/rls_and_roles.sql'), 'utf8');
  run(
    'sudo',
    ['-n', '-u', 'postgres', 'psql', '-X', '-v', 'ON_ERROR_STOP=1', '-d', databaseName],
    { input: rlsSql }
  );

  run('npm', ['run', 'db:seed:plans']);
  console.log('PostgreSQL local est prêt. Les identifiants sont enregistrés dans apps/web/.env.');
}

main().catch((error) => {
  const message = secrets.reduce(
    (safeMessage, secret) => safeMessage.split(secret).join('[masqué]'),
    error.message
  );
  console.error(`Configuration PostgreSQL locale impossible : ${message}`);
  process.exitCode = 1;
});
